// проверялась только «на глаз»: тесты убеждались, что поле конечно, но не
// проверяли, что оно вообще является решением. Проверка на поверхности тела
// показала две настоящие ошибки (обе исправлены здесь):
//
//   1) ЗНАК ДУБЛЕТА. Возмущение скорости складывалось с набегающим потоком,
//      а в потенциале сферы оно ВЫЧИТАЕТСЯ:
//          u = U - (a³ / 2r³) * (3(U·r̂)r̂ - U)
//      Из-за перевёрнутого знака в носовой точке торможения скорость была 2U
//      вместо нуля, а на поверхности нормальная составляющая была 2U вместо 0:
//      поток «протыкал» тело. Ошибка была не видна в интерфейсе, потому что
//      выглядела как обычное поле, но частицы, линии тока и Cp (когда LBM
//      выключен) считались по нефизическому полю.
//   2) ФИКТИВНЫЙ shapeFactor. Множитель 1/(1+0.15(elong-1)) «поправлял форму»
//      и умножал только возмущение, но не набегающий поток. Тем самым он ломал
//      условие непротекания: для тела 4:0.5:0.5 нормальная скорость на стенке
//      доходила до 51 % от U. Убран: форма тела полностью учитывается
//      преобразованием координат ниже, и с правильным знаком условие
//      непротекания выполняется точно (проверяется тестом).
//
// КАК СЧИТАЕТСЯ. Тело с полуосями r = (rx, ry, rz) отображается в единичную
// сферу заменой x' = x / r. В преобразованном пространстве берётся точное
// решение для сферы, после чего скорость возвращается в физическое:
//
//      U' = U / r          (чтобы на бесконечности u = U)
//      u' = U' - (1/2r'³)(3(U'·r̂')r̂' - U')
//      u_i = r_i * u'_i
//
// Последнее соотношение — не произвольный «масштаб»: именно так выполняется
// условие непротекания u·n = 0 на поверхности ЛЮБОГО такого эллипсоида,
// потому что на единичной сфере u'·x' = 0, а нормаль эллипсоида в физическом
// пространстве пропорциональна x'_i / r_i. Для шара преобразование сводится
// к классической формуле, что видно по тесту.
//
// Внутри тела скорость равна нулю (приближение «непроницаемое тело»): там, где
// решение даёт u = U, возвращается 0, чтобы вызывающий код не складывал
// набегающий поток с «минус набегающим».
//
// Модуль намеренно header-only и не зависит от glm, OpenGL и ImGui: те же
// функции вызываются из CUDA-ядра без изменений.
// =====================================================

#include <cmath>

namespace aeros_potential {

// Значение скорости жидкости в точке p для эллипсоида с центром c и полуосями
// rad, обтекаемого потоком U. Внутри тела — нуль.
inline void ellipsoidVelocity(const float p[3], const float c[3], const float rad[3],
                              const float U[3], float out[3]) {
    out[0] = U[0];
    out[1] = U[1];
    out[2] = U[2];

    // Полуоси не могут быть нулевыми: иначе деление на ноль и «бесконечное»
    // ускорение потока. Один и тот же минимум во всех ветках — без разрывов.
    const float rx = rad[0] > 1e-6f ? rad[0] : 1e-6f;
    const float ry = rad[1] > 1e-6f ? rad[1] : 1e-6f;
    const float rz = rad[2] > 1e-6f ? rad[2] : 1e-6f;

    const float dx = (p[0] - c[0]) / rx;
    const float dy = (p[1] - c[1]) / ry;
    const float dz = (p[2] - c[2]) / rz;
    const float r2 = dx * dx + dy * dy + dz * dz;

    // Внутри тела (и ровно на поверхности) — покой. Раньше здесь возвращалось
    // -U с тем, чтобы вызывающий код получил ноль; теперь результат сразу
    // однозначен и не зависит от того, как его сложат.
    if (!(r2 > 1.0f)) {
        out[0] = out[1] = out[2] = 0.0f;
        return;
    }

    const float r = std::sqrt(r2);
    const float inv3 = 1.0f / (r2 * r);      // 1 / r'³

    // Набегающий поток в преобразованном пространстве и нормаль к сфере.
    const float Upx = U[0] / rx, Upy = U[1] / ry, Upz = U[2] / rz;
    const float nx = dx / r, ny = dy / r, nz = dz / r;
    const float Ur = Upx * nx + Upy * ny + Upz * nz;

    // Возмущение для сферы, ЗНАК МИНУС (см. вывод в заголовке файла).
    const float k = -0.5f * inv3;
    const float px = k * (3.0f * Ur * nx - Upx);
    const float py = k * (3.0f * Ur * ny - Upy);
    const float pz = k * (3.0f * Ur * nz - Upz);

    // Обратно в физическое пространство: u_i = r_i * u'_i.
    out[0] = U[0] + px * rx;
    out[1] = U[1] + py * ry;
    out[2] = U[2] + pz * rz;
}

// Доля нормальной скорости на поверхности эллипсоида (для тестов и диагностики):
// u·n, нормированное на |U|. У правильного решения — 0.
inline float surfaceNormalVelocity(const float dir[3], const float c[3], const float rad[3],
                                   const float U[3]) {
    // Точка чуть снаружи поверхности вдоль луча dir.
    const float k = 1.001f;
    const float p[3] = {c[0] + dir[0] * rad[0] * k,
                        c[1] + dir[1] * rad[1] * k,
                        c[2] + dir[2] * rad[2] * k};
    float v[3];
    ellipsoidVelocity(p, c, rad, U, v);
    // Нормаль к эллипсоиду в этой точке: n ∝ (x-c)/r².
    const float rx = rad[0] > 1e-6f ? rad[0] : 1e-6f;
    const float ry = rad[1] > 1e-6f ? rad[1] : 1e-6f;
    const float rz = rad[2] > 1e-6f ? rad[2] : 1e-6f;
    float nx = dir[0] / rx, ny = dir[1] / ry, nz = dir[2] / rz;
    const float nl = std::sqrt(nx * nx + ny * ny + nz * nz);
    if (!(nl > 1e-12f)) return 0.0f;
    nx /= nl; ny /= nl; nz /= nl;
    return v[0] * nx + v[1] * ny + v[2] * nz;
}

}  // namespace aeros_potential
