// =====================================================
// Вязкость воздуха по Сазерленду — ЕДИНСТВЕННЫЙ источник формулы.
//
// Зачем вынесено: формула была скопирована в семи местах (flow_field.cpp ×2,
// forces.cpp, particles.cpp ×2, lbm.cpp ×2), и в initLBM() температура
// «переводилась в кельвины» второй раз — `airTemperature + 273.15f`, хотя
// airTemperature УЖЕ задана в кельвинах (atmosphere.h: `extern float
// airTemperature; // K`, то же в flow_params.h и в панели ISA, которая печатает
// `%.1f K (%.1f C)` как airTemperature и airTemperature-273.15). При 288.15 K
// это давало T = 561.3 K и вязкость 2.82e-5 вместо 1.79e-5 (+58%), а следом —
// заниженное в 1.6 раза число Рейнольдса, завышенную nuPhys и другой tau:
// решатель стартовал не с той вязкостью, которую показывала панель.
//
// ВАЖНО: аргумент — КЕЛЬВИНЫ. Контрольные точки (используются в тесте):
//   T = 273.15 K  ->  mu = mu0 = 1.716e-5 Па*с ровно по построению формулы;
//   T = 288.15 K  ->  mu ~ 1.7894e-5 Па*с (ISA на уровне моря);
//   mu монотонно растёт с температурой.
// =====================================================
inline float airSutherlandViscosity(float T_kelvin) {
    float T = T_kelvin;
    if (!std::isfinite(T) || T < 50.0f) T = 288.15f;   // защита от мусора и от °C
    if (T > 2000.0f) T = 2000.0f;
    const float T0 = 273.15f, S = 110.4f, mu0 = 1.716e-5f;
    float mu = mu0 * std::pow(T / T0, 1.5f) * (T0 + S) / (T + S);
    if (!std::isfinite(mu) || mu < 1e-7f) mu = 1.81e-5f;
    return mu;
}

