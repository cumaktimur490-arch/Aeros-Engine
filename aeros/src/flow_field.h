// v1.30.0 — ЯВНЫЙ выбор источника скорости для точки.
//
// До этого источник определялся условиями внутри computeVelocityFieldCPU(), и
// проверить «чем на самом деле интегрируются частицы» можно было только читая
// тело функции. Теперь решение вынесено в отдельную функцию: её вызывают и
// computeVelocityFieldCPU (все стадии интегрирования частиц, линии тока, цвет),
// и headless-тесты, и диагностика, поэтому разойтись они не могут.
//
// Правило (прежнее, ничего не переключено):
//   LBM включён и инициализирован ->
//       точка в твёрдом теле решателя        = LBMSolid      (скорость 0);
//       точка внутри домена решателя         = LBM           (интерполированное
//                                                            поле lbmUxWorld..);
//       точка вне домена                     = LBMFreestream (невозмущённый поток);
//   LBM выключен                             = Analytical    (потенциал эллипсоида
//                                                            + поправки).
// =====================================================
enum class AeroVelocitySource {
    LBM = 0,          // поле, посчитанное решателем LBM
    LBMSolid,         // тело решателя: скорость равна нулю
    LBMFreestream,    // вне домена LBM: набегающий поток
    Analytical        // аналитическое поле (режим без LBM)
};

AeroVelocitySource aeroVelocitySourceAt(const glm::vec3& p, const FlowParams& prm);
